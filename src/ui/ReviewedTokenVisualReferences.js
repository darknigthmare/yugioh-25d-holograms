export function applyReviewedTokenVisualReference(profile) {
  if (!profile || !Object.hasOwn(REVIEWED_TOKEN_VISUAL_REFERENCES, profile.tokenCode)) return profile;
  const reference = REVIEWED_TOKEN_VISUAL_REFERENCES[profile.tokenCode];
  return {
    ...profile, ...reference,
    tokenVisual: {
      ...profile.tokenVisual,
      visualBasis: 'printed-token-art',
      referenceArtPath: reference.referenceArtPath,
      referenceSet: reference.referenceSet
    }
  };
}
