    const shape=new THREE.BoxGeometry(1,1,1,2,1,1),p=shape.attributes.position;
    for(let i=0;i<p.count;i+=1)p.setY(i,p.getY(i)>0?0.6-Math.abs(p.getX(i))*1.2:-0.13);
    p.needsUpdate=true;shape.computeVertexNormals();shape.userData.pitchedRoof=true;return shape;
