import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';

const auditUrl = new URL('../docs/audits/artifacts/native-field-runtime-2026-10-08.json', import.meta.url);
const outputUrl = new URL('../src/ui/NativeFieldCoverageSnapshot.js', import.meta.url);

/** A compact factual view, without shipping native scenario decks to the UI. */
export function nativeFieldCoverageSnapshot(report) {
  assert.ok(Array.isArray(report.matrix));
  assert.equal(new Set(report.matrix.map(row => row.canonicalCode)).size, report.matrix.length);
  const ids = key => report.matrix.filter(row => row[key] === true).map(row => String(row.canonicalCode));
  const summary = { catalogue: report.matrix.length, bundled: ids('bundled').length,
    initialized: ids('initialized').length, effectTested: ids('effectTested').length,
    integrationTested: ids('integrationTested').length,
    scenarios: report.scenarios.length, passedScenarios: report.scenarios.filter(row => row.status === 'passed').length };
  assert.deepEqual(summary, report.summary, 'Native evidence summary must agree with its individual records');
  const paths = Object.fromEntries(report.matrix.filter(row => row.scriptPath !== `official/c${row.canonicalCode}.lua`)
    .map(row => [String(row.canonicalCode), row.scriptPath]));
  return { generatedOn: report.generatedOn, corePackage: report.corePackage,
    corePackageVersion: report.corePackageVersion, nativeApi: report.nativeApi,
    coreRevision: report.coreRevision, coreWasmSha256: report.coreWasmSha256,
    scriptsCommit: report.resources.sources.scripts.commit,
    databaseCommit: report.resources.sources.database.commit,
    evidencePath: 'docs/audits/artifacts/native-field-runtime-2026-10-08.json', summary,
    bundledCardIds: ids('bundled'), initializedCardIds: ids('initialized'),
    effectTestedCardIds: ids('effectTested'), integrationTestedCardIds: ids('integrationTested'),
    scriptSourceOverrides: paths };
}

export async function generateNativeFieldCoverage() {
  const snapshot = nativeFieldCoverageSnapshot(JSON.parse(await readFile(auditUrl, 'utf8')));
  const body = JSON.stringify(snapshot, null, 2);
  const source = `// Generated by scripts/generate-native-field-coverage.mjs from individual audit records.\n`
    + `// Source/initialization availability is not a certificate of every card-effect branch.\n`
    + `const snapshot = ${body};\n`
    + `for (const key of ['nativeApi', 'summary', 'bundledCardIds', 'initializedCardIds', 'effectTestedCardIds', 'integrationTestedCardIds', 'scriptSourceOverrides']) Object.freeze(snapshot[key]);\n`
    + `export const NATIVE_FIELD_COVERAGE_SNAPSHOT = Object.freeze(snapshot);\n`;
  await writeFile(outputUrl, source);
  return snapshot;
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const snapshot = await generateNativeFieldCoverage();
  console.log(JSON.stringify(snapshot.summary));
}
